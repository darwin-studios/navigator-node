import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format as formatSource, resolveConfig } from 'prettier';
import ts from 'typescript';
import { build } from 'esbuild';

// Compile the canonical validators into the published package. Consumers need
// neither a private workspace package nor the OpenAI SDK. Never hand-edit output.
const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const monorepoRoot = resolve(packageRoot, '../../../..');
const root = await access(resolve(monorepoRoot, 'packages/agent-contracts/src/act-openai.ts'))
  .then(() => monorepoRoot)
  .catch(() => packageRoot);
const entry = resolve(packageRoot, 'src/openai/index.ts');
const prettierConfig = (await resolveConfig(resolve(monorepoRoot, '.prettierrc'))) ?? { singleQuote: true, jsxSingleQuote: true, tabWidth: 2, printWidth: 120, semi: true, trailingComma: 'all' };
const emitted = new Map();
const program = ts.createProgram([entry], {
  rootDir: root,
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  strict: true,
  skipLibCheck: true,
  declaration: true,
  noEmitOnError: true,
  outDir: resolve(root, 'apps/navigator/api/sdk/generated/openai-build'),
});
const result = program.emit(undefined, (path, text) => emitted.set(basename(path), text));
const diagnostics = [...ts.getPreEmitDiagnostics(program), ...result.diagnostics];
if (diagnostics.length)
  throw new Error(
    ts.formatDiagnosticsWithColorAndContext(diagnostics, {
      getCurrentDirectory: () => root,
      getCanonicalFileName: (name) => name,
      getNewLine: () => '\n',
    }),
  );
const banner = '// Generated by apps/navigator/api/sdk/scripts/build-openai.mjs from canonical Act sources. Do not edit.\n';
for (const name of [
  'index',
  'act-openai',
  'act-public',
  'act-threads',
  'act-thread-responses',
  'simple-act-responses',
  'composer',
  'composer-runtime',
  'agent-component-library',
  'operation-guidance',
  'agent-appearance',
  'thread-tool-selection',
]) {
  for (const format of ['esm', 'cjs']) {
    for (const declaration of [false, true]) {
      const source = emitted.get(`${name}${declaration ? '.d.ts' : '.js'}`);
      if (!source) throw new Error(`Missing compiler output: ${name}`);
      const extension = declaration ? (format === 'esm' ? 'd.mts' : 'd.ts') : format === 'esm' ? 'mjs' : 'js';
      const runtimeExtension = format === 'esm' ? 'mjs' : 'js';
      let content = source
        .replace(/@repo\/agent-contracts\/([\w-]+)(?=['"])/g, `./$1.${runtimeExtension}`)
        .replaceAll('../../../../../../packages/agent-contracts/src/act-openai.js', `./act-openai.${runtimeExtension}`)
        .replaceAll('../../generated/esm/Client.mjs', `../Client.${runtimeExtension}`)
        .replace(/\.\/canonical\/((?:act-|simple-act-|thread-)[\w-]+|composer)(?:\.js)?(?=['"])/g, `./$1.${runtimeExtension}`)
        .replace(/\.\/((?:act-|simple-act-|thread-)[\w-]+|composer)(?:\.js)?(?=['"])/g, `./$1.${runtimeExtension}`);
      if (declaration) content = content.replace(/export \{ createAgentView, renderAgentView \} from ['"](?:@darwinui\/core|\.\/agent-view\.js)['"];?\n/g, '');
      content = content.replace(/\.\/((?:composer-runtime|agent-component-library))(?:\.js)?(?=['"])/g, `./$1.${runtimeExtension}`);
      if (name === 'composer' && !declaration) {
        const bundled = await build({ absWorkingDir: root, entryPoints: [root === monorepoRoot ? resolve(root, 'packages/agent-contracts/src/composer.ts') : resolve(packageRoot, 'src/openai/canonical/composer.ts')], bundle: true, write: false, platform: 'node', target: 'node20', format: format === 'esm' ? 'esm' : 'cjs', external: ['zod'], logLevel: 'silent' });
        content = bundled.outputFiles[0].text;
      }
      if (format === 'cjs' && !declaration)
        content = ts.transpileModule(content, {
          compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
        }).outputText;
      if (content.includes('@repo/')) throw new Error('Private workspace import escaped the SDK build');
      const path = resolve(packageRoot, `generated/${format}/openai/${name}.${extension}`);
      content = banner + content;
      // TypeScript's second CommonJS transpilation emits a different layout than
      // the repository formatter. Normalize it here so generation, formatting,
      // and --check remain deterministic.
      if (format === 'cjs') content = await formatSource(content, { ...prettierConfig, filepath: path });
      if (process.argv.includes('--check')) {
        if ((await readFile(path, 'utf8').catch(() => '')) !== content)
          throw new Error(`Stale OpenAI compatibility build: ${path}`);
      } else {
        await mkdir(dirname(path), { recursive: true });
        await writeFile(path, content);
      }
    }
  }
}
